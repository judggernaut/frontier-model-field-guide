"""Render fully worked interview examples in one consistent template.

Each example is a dict:
  id, title, source, prompt                      what was asked, and by whom
  ask:    [(question, why it matters)]          clarifying questions, with what each answer changes
  approaches: [(name, pros, cons)], verdict      options considered and the choice
  steps:  [(title, text, snippet_name|None)]     build it up, one version at a time
  edges:  [(case, handling)]
  complexity                                      one paragraph
  math:   optional HTML (worked numbers)
  followups: [(question, answer)]
  say                                             what to say out loud in the first minute
"""
import html, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def load_snippets(*files):
    snips = {}
    for f in files:
        src = open(os.path.join(ROOT, 'tools', 'worked', f)).read()
        for m in re.finditer(r'# >>> (\w+)\n(.*?)\n# <<<', src, re.S):
            snips[m.group(1)] = m.group(2).rstrip()
    return snips

def code(s, lang='python'):
    return f'<pre class="code" data-lang="{lang}"><code>{html.escape(s.strip(chr(10)), quote=False)}</code></pre>'

def render(ex, snips):
    o = [f'<h3 id="{ex["id"]}">{ex["title"]}</h3>']
    o.append(f'<p class="wk-src">{ex["source"]}</p>')
    o.append(f'<div class="callout example"><span class="tag">The prompt</span><div>{ex["prompt"]}</div></div>')
    if ex.get('say'):
        o.append(f'<div class="callout ask"><span class="tag">First minute, out loud</span><div>{ex["say"]}</div></div>')
    o.append('<h4>1 · Questions to ask before building</h4><div class="tw"><table><thead><tr><th>Ask</th><th>Why it changes the solution</th></tr></thead><tbody>')
    o += [f'<tr><td>{q}</td><td>{w}</td></tr>' for q, w in ex['ask']]
    o.append('</tbody></table></div>')
    o.append('<h4>2 · Approaches, pros and cons</h4><div class="tw"><table><thead><tr><th>Approach</th><th>Pros</th><th>Cons</th></tr></thead><tbody>')
    o += [f'<tr><td><b>{n}</b></td><td>{p}</td><td>{c}</td></tr>' for n, p, c in ex['approaches']]
    o.append(f'</tbody></table></div><p><b>Choice:</b> {ex["verdict"]}</p>')
    if ex.get('math'):
        o.append(f'<h4>The numbers</h4>{ex["math"]}')
    o.append('<h4>3 · Build it step by step</h4><ol class="steps">')
    for t, txt, sn in ex['steps']:
        body = f'<b>{t}.</b> {txt}'
        if sn: body += code(snips[sn])
        o.append(f'<li><div>{body}</div></li>')
    o.append('</ol>')
    o.append('<h4>4 · Edge cases</h4><div class="tw"><table><thead><tr><th>Case</th><th>Handling</th></tr></thead><tbody>')
    o += [f'<tr><td>{c}</td><td>{h}</td></tr>' for c, h in ex['edges']]
    o.append('</tbody></table></div>')
    if ex.get('complexity'):
        o.append(f'<h4>5 · Complexity and cost</h4><p>{ex["complexity"]}</p>')
    if ex.get('followups'):
        o.append('<h4>6 · Follow-ups</h4>')
        o += [f'<details class="qa"><summary>{q}</summary><p>{a}</p></details>' for q, a in ex['followups']]
    return '\n'.join(o)

def chapter(sid, nav, h2, intro_html, examples, snips, outro=''):
    toc = ''.join(f'<li><a href="#{e["id"]}">{e["title"]}</a></li>' for e in examples)
    body = '\n\n'.join(render(e, snips) for e in examples)
    return (f'<!-- GENERATED by tools/worked/*.py. Edit the content module, then run tools/worked/build_chapters.py -->\n'
            f'<section id="{sid}" data-title="{nav}">\n<h2>{h2}</h2>\n{intro_html}\n'
            f'<div class="callout note"><span class="tag">In this chapter</span><div><ol>{toc}</ol></div></div>\n'
            f'{body}\n{outro}\n</section>\n')
